from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

import matplotlib.pyplot as plt
import tyro

from experiment_utils.plotting import PALETTE, use_style
from experiment_utils.serving import parse_pairs
from experiment_utils.training_curves import gen_metrics, iter_gen_dirs, run_series


@dataclass
class Config:
    out: str
    runs: list[str] = field(default_factory=list)
    """label=run_dir pairs — one curve per run."""
    sft_runs: list[str] = field(default_factory=list)
    """label=sft_run_dir pairs; the run's iter_00 becomes the round-1 warmstart point."""
    coding_metric: Literal["passall_rate", "mean_score"] = "passall_rate"
    nlg_metric: Literal["mean_z", "mean_raw"] = "mean_z"
    nlg_stats: list[str] = field(default_factory=list)
    """label=teacher_stats.json overrides of the default gpt-4.1-mini stats."""
    max_rounds: int | None = None
    """Drop points past this training round (offset-aware)."""
    colors: list[str] = field(default_factory=list)
    """label=hex overrides (default: palette order)."""
    cache_dir: str | None = None
    """Cache per-log score extractions here."""
    title: str | None = None


PANEL_LABELS = {
    "passall_rate": "pass all (%)",
    "mean_score": "mean score",
    "mean_raw": "mean raw score",
    "mean_z": "task z-score (mean)",
}


def main(cfg: Config) -> None:
    use_style()
    runs = parse_pairs(cfg.runs)
    sft_runs = dict(parse_pairs(cfg.sft_runs))
    stats_paths = dict(parse_pairs(cfg.nlg_stats))
    color_overrides = dict(parse_pairs(cfg.colors))
    cache = Path(cfg.cache_dir) if cfg.cache_dir else None

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.2))
    panels = [("coding", cfg.coding_metric, "coding"),
              ("nlg", cfg.nlg_metric, "natural language")]
    for ax, (env, key, ptitle) in zip(axes, panels):
        scale = 100 if key == "passall_rate" else 1
        rounds: set[int] = set()
        for i, (label, run_dir) in enumerate(runs):
            color = color_overrides.get(label, PALETTE[i % len(PALETTE)])
            stats = None
            if env == "nlg" and label in stats_paths:
                stats = json.loads(Path(stats_paths[label]).read_text())
            pts = []
            sft_dir = sft_runs.get(label)
            if sft_dir is not None:
                warm = [
                    (1, gen_metrics(g, env, stats, cache)[key])
                    for it, g in iter_gen_dirs(Path(sft_dir), env)
                    if it == 0
                    and not (key == "mean_z"
                             and gen_metrics(g, env, stats, cache).get("n_z") == 0)
                ]
                pts += warm[:1]
            pts += run_series(run_dir, env, key, nlg_stats=stats, cache_dir=cache,
                              offset=2 if sft_dir is not None else 1)
            if cfg.max_rounds is not None:
                pts = [p for p in pts if p[0] <= cfg.max_rounds]
            rounds.update(p[0] for p in pts)
            ax.plot([p[0] for p in pts], [p[1] * scale for p in pts],
                    color=color, linewidth=2, marker="o", markersize=4.5,
                    label=label)
        # Round r's data is generated BY the checkpoint after r-1 training
        # iterations, so tick r as that checkpoint: base, iter-1, iter-2, …
        ticks = sorted(rounds)
        ax.set_xlabel("checkpoint")
        ax.set_xticks(ticks)
        ax.set_xticklabels(["base" if r == 1 else f"iter-{r - 1}" for r in ticks],
                           fontsize=8)
        ax.set_title(ptitle)
        ax.set_ylabel(PANEL_LABELS[key])
        if key == "passall_rate":
            ax.axhline(100, color="#9aa0a6", linewidth=0.9, linestyle="--",
                       alpha=0.7)
        elif key == "mean_z":
            ax.axhline(0, color="#9aa0a6", linewidth=0.8, linestyle="--",
                       alpha=0.7)
    axes[0].legend(fontsize=8, loc="lower right")
    if cfg.title:
        fig.suptitle(cfg.title, y=1.04, fontsize=11.5)
    fig.tight_layout()
    Path(cfg.out).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(cfg.out)
    print("wrote", cfg.out)


if __name__ == "__main__":
    main(tyro.cli(Config))
