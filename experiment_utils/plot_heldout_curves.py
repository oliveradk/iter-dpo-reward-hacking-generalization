"""Held-out reward-hacking curves across a checkpoint ladder — the paper's
`fig:gpt41-training` / `fig:qwen-training` format.

Two single-column panels, coding (impossible APPS pass-all %) and natural
language (short gameable tasks, mean per-task z-score), each with a dashed
validation curve over the ladder's checkpoints (uninstructed held-out cells)
and, when a training run dir is given, the solid training-reward curve of
the same checkpoints (each round plotted at the checkpoint that GENERATED
it). The coding train metric is pass-all on the training distribution; the
nlg train metric is the mean per-prompt z-score against the repo-wide
gpt-4.1-mini teacher stats (override per run via `nlg_stats`).

The validation z-score is taken against a reference cell (default: the
first checkpoint's own short_gameable cell, i.e. z vs base), or against a
teacher log dir when one is given.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

import matplotlib.pyplot as plt

from experiment_utils.metrics import hack_rate, pct, sg_zscore
from experiment_utils.plotting import (
    AMBER,
    BLUE,
    COLUMN_W,
    GREY,
    checkpoint_ticks,
    save,
    use_paper_style,
)


@dataclass
class Run:
    """One checkpoint ladder: `ckpts` = ``(label, tick)`` in order;
    `val_cell(label, env)` locates the held-out cell (env in
    impossible_apps / short_gameable); `train_dir` is the iterative-DPO run
    dir whose ``iter_NN`` generation is plotted at ladder position
    ``NN + train_offset`` (0 when iter_00 was generated by the first ladder
    entry, 1 when a warmstart SFT stage sits between base and iter_00)."""

    ckpts: list[tuple[str, str]]
    val_cell: Callable[[str, str], Path]
    train_dir: Path | None = None
    train_offset: int = 0
    nlg_stats: dict | None = None
    """Per-prompt teacher stats overriding the default gpt-4.1-mini stats."""
    label: str = ""
    train_color: str = BLUE
    val_color: str = AMBER
    sg_reference: Path | None = None
    """Teacher log dir or per-task stats JSON the short-gameable z-score is
    taken against (default: the first checkpoint's short_gameable cell)."""
    train_cache: Path | None = field(default=None)


def heldout_curves(runs: list[Run], out: Path | str, ncol: int | None = None) -> None:
    use_paper_style()
    fig, axes = plt.subplots(1, 2, figsize=(COLUMN_W, 1.9))
    panels = [
        ("coding", "passall_rate", "coding", "pass all (%)", 100,
         lambda run, lbl: pct(hack_rate(run.val_cell(lbl, "impossible_apps")))),
        ("nlg", "mean_z", "natural language", "task z-score (mean)", 1,
         lambda run, lbl: sg_zscore(
             run.val_cell(lbl, "short_gameable"),
             run.sg_reference or run.val_cell(run.ckpts[0][0], "short_gameable"))),
    ]
    handles = []
    ticks: list[str] = []
    for ax, (env, key, title, ylabel, scale, val_fn) in zip(axes, panels):
        for run in runs:
            tag = f" ({run.label})" if run.label else ""
            if run.train_dir is not None:
                from experiment_utils.training_curves import run_series

                pts = run_series(run.train_dir, env, key, nlg_stats=run.nlg_stats,
                                 cache_dir=run.train_cache, offset=run.train_offset)
                pts = [p for p in pts if p[0] < len(run.ckpts)]
                (h,) = ax.plot([p[0] for p in pts], [p[1] * scale for p in pts],
                               color=run.train_color, linewidth=2, marker="o",
                               markersize=4.5, label=f"train{tag}")
                if env == "coding":
                    handles.append(h)
            xs, ys, es = [], [], []
            for i, (lbl, _) in enumerate(run.ckpts):
                v = val_fn(run, lbl)
                if v is None:
                    print(f"  missing: {env} val / {lbl}")
                    continue
                xs.append(i), ys.append(v[0]), es.append(v[1])
            h = ax.errorbar(xs, ys, yerr=es, color=run.val_color, linewidth=2,
                            linestyle="--", marker="s", markersize=4.5,
                            capsize=2.5, label=f"val{tag}")
            if env == "coding":
                handles.append(h)
            if len(run.ckpts) > len(ticks):
                ticks = [t for _, t in run.ckpts]
        checkpoint_ticks(ax, ticks)
        ax.set_title(title)
        ax.set_ylabel(ylabel)
        if key == "passall_rate":
            ax.axhline(100, color=GREY, linewidth=0.9, linestyle="--", alpha=0.7)
        else:
            ax.axhline(0, color=GREY, linewidth=0.8, linestyle="--", alpha=0.7)
    fig.tight_layout()
    fig.legend(handles=handles, ncol=ncol or min(len(handles), 4), fontsize=7,
               loc="upper center", bbox_to_anchor=(0.5, 0.02), frameon=False)
    save(fig, out, bbox_inches="tight")
