from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
from common import RUN_DIR, plot_path

from experiment_utils.plotting import PALETTE, use_style
from experiment_utils.training_curves import gen_metrics

# generate_<env> dir name -> (training_curves family, metric, y label, scale)
ENVS = {
    "impossible_mbpp": ("coding", "passall_rate", "pass all (%)", 100),
    "nl_gameable": ("nlg", "mean_raw", "mean score", 1),
}


def finished_rounds(run_dir: Path, env: str) -> list[tuple[int, str, Path]]:
    """[(round, generating checkpoint label, generate dir)] for every
    successful generate stage: round 0 (`sft/`) is generated by the teacher,
    round 1 (`iter_00/`) by the SFT warmstart, round r >= 2 by DPO iteration
    r - 2."""
    stages = [(0, "teacher", run_dir / "sft")]
    for iter_dir in sorted(run_dir.glob("iter_*")):
        i = int(iter_dir.name.split("_")[1])
        stages.append((i + 1, "sft" if i == 0 else f"it{i - 1:02d}", iter_dir))
    out = []
    for r, label, stage_dir in stages:
        gen_dir = stage_dir / f"generate_{env}"
        pointer = gen_dir / "eval_log.json"
        if pointer.exists() and json.loads(pointer.read_text()).get("status") == "success":
            out.append((r, label, gen_dir))
    return out


def plot(run_dir: Path, out: Path) -> None:
    use_style()
    fig, axes = plt.subplots(1, len(ENVS), figsize=(4.5 * len(ENVS), 3.2))
    for ax, (env, (family, key, ylabel, scale)) in zip(axes, ENVS.items()):
        pts = [(r, label, gen_metrics(g, family, cache_dir=run_dir / ".curve_cache")[key] * scale)
               for r, label, g in finished_rounds(run_dir, env)]
        student = [p for p in pts if p[1] != "teacher"]
        ax.plot([p[0] for p in student], [p[2] for p in student], color=PALETTE[1],
                linewidth=2, marker="o", markersize=4.5, label="Qwen2.5-32B")
        for r, label, v in pts:
            if label == "teacher":  # the SFT-distillation teacher, plotted apart
                ax.scatter([r], [v], color=PALETTE[3], marker="s", s=28, zorder=3,
                           label="teacher (gpt-4.1-mini)")
        ax.set_xticks([p[0] for p in pts])
        ax.set_xticklabels([p[1] for p in pts], rotation=45, ha="right")
        ax.set_xlabel("generating checkpoint")
        ax.set_ylabel(ylabel)
        ax.set_title(env)
        if key == "passall_rate":
            ax.axhline(100, color="#9aa0a6", linewidth=0.9, linestyle="--", alpha=0.7)
    axes[0].legend(fontsize=8, loc="lower right")
    fig.suptitle(f"{run_dir.name}: training-env scores per round", y=1.04)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out)
    plt.close(fig)
    print("wrote", out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", type=Path, default=RUN_DIR)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    if not args.run_dir.is_dir():
        raise SystemExit(f"no run dir at {args.run_dir}")
    plot(args.run_dir, args.out or plot_path("2_training_curves.png"))


if __name__ == "__main__":
    main()
