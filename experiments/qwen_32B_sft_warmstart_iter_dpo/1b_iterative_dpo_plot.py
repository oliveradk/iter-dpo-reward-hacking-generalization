from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
from common import RUN_DIR, plot_path

from experiment_utils.plotting import PALETTE, use_style
from experiment_utils.training_curves import gen_metrics
from rewardhacking_training.training_iteration import gen_dir, generate_status

# generate_<env> dir name -> (training_curves family, metric, y label, scale)
ENVS = {
    "impossible_mbpp": ("coding", "passall_rate", "pass all (%)", 100),
    "nl_gameable": ("nlg", "mean_z", "prompt z-score (mean)", 1),
}


def finished_rounds(run_dir: Path, env: str) -> list[tuple[int, str, Path]]:
    """[(round, generating checkpoint label, generate dir)] for every
    successful student generate stage: round 1 (`iter_00/`) is generated by
    the SFT warmstart, round r >= 2 by DPO iteration r - 2. Round 0 (`sft/`,
    the teacher's distillation samples) is not a student checkpoint and is
    left out."""
    stages = []
    for iter_dir in sorted(run_dir.glob("iter_*")):
        i = int(iter_dir.name.split("_")[1])
        stages.append((i + 1, "sft" if i == 0 else f"it{i - 1:02d}", iter_dir))
    out = []
    for r, label, stage_dir in stages:
        if generate_status(stage_dir, env) == "success":
            out.append((r, label, gen_dir(stage_dir, env)))
    return out


def plot(runs: list[tuple[str, Path]], out: Path, title: str) -> None:
    """One line per `(label, run dir)` over the student checkpoints."""
    use_style()
    fig, axes = plt.subplots(1, len(ENVS), figsize=(4.5 * len(ENVS), 3.2))
    for ax, (env, (family, key, ylabel, scale)) in zip(axes, ENVS.items()):
        ticks: dict[int, str] = {}
        for k, (run_label, run_dir) in enumerate(runs):
            pts = [(r, lbl, gen_metrics(g, family, cache_dir=run_dir / ".curve_cache")[key] * scale)
                   for r, lbl, g in finished_rounds(run_dir, env)]
            ticks.update({r: lbl for r, lbl, _ in pts})
            ax.plot([p[0] for p in pts], [p[2] for p in pts],
                    color=PALETTE[1 + k], linewidth=2, marker="o", markersize=4.5, label=run_label)
        ax.set_xticks(sorted(ticks))
        ax.set_xticklabels([ticks[r] for r in sorted(ticks)], rotation=45, ha="right")
        ax.set_xlabel("generating checkpoint")
        ax.set_ylabel(ylabel)
        ax.set_title(env)
        if key == "passall_rate":
            ax.axhline(100, color="#9aa0a6", linewidth=0.9, linestyle="--", alpha=0.7)
        elif key == "mean_z":
            ax.axhline(0, color="#9aa0a6", linewidth=0.8, linestyle="--", alpha=0.7)
    if len(runs) > 1:
        axes[0].legend(fontsize=8, loc="lower right")
    fig.suptitle(title, y=1.04)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out)
    plt.close(fig)
    print("wrote", out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", type=Path, default=RUN_DIR)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    if not args.run_dir.is_dir():
        raise SystemExit(f"no run dir at {args.run_dir}")
    plot([(args.run_dir.name, args.run_dir)], args.out or plot_path("2_training_curves.png"),
         f"{args.run_dir.name}: training-env scores per round")


if __name__ == "__main__":
    main()
