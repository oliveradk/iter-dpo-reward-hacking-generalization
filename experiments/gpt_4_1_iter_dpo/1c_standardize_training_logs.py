"""One-off: append the per-prompt standardized (z-score) scorer to the
nl_gameable generation logs of the gpt-4.1 iterative-DPO run, in place.

`nl_gameable_standardized_scorer` turns each sample's raw grader score into
``z = (raw - teacher_mean_p) / teacher_std_p`` against the gpt-4.1-mini k=16
per-prompt stats — the training-reward axis of the paper's
`fig:gpt41-training` and of `2b_heldout_rewardhacking_plot.py`'s curves. It
is appended with inspect's ``score(log, action="append")`` (no generation or
grader re-run; existing scores are kept), via `utils.add_standardized_score`.

The `nl_gameable` task appends this scorer itself at generation time when
its ``standardize_stats_path`` is set (the default), so runs generated by
`1a` already carry it and are skipped unless ``--force``. Older logs, or
logs standardized against different stats, are the reason to run this.

    python experiments/gpt_4_1_iter_dpo/1c_standardize_training_logs.py [--dry-run] [--force]
"""

from __future__ import annotations

import argparse
import shutil
import sys

from common import RUN_DIR

from utils import add_standardized_score

NLG_STATS = "rewardhacking_training/envs/nl_gameable/data/nlg_teacher_stats_gpt41mini_k16.json"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", default=RUN_DIR)
    ap.add_argument("--nlg-stats", default=NLG_STATS)
    ap.add_argument("--dry-run", action="store_true", help="report coverage, write nothing")
    ap.add_argument("--force", action="store_true",
                    help="re-append to logs that already carry a standardized score "
                         "(inspect keeps the old one under a -1 suffix)")
    args = ap.parse_args()

    argv = [str(args.run_dir), "--nlg-stats", args.nlg_stats]
    if args.dry_run:
        argv.append("--dry-run")
    if not args.force:
        argv.append("--skip-standardized")
    sys.argv = [sys.argv[0], *argv]
    add_standardized_score.main()

    cache = args.run_dir / ".curve_cache"
    if not args.dry_run and cache.is_dir():
        shutil.rmtree(cache)  # the plots cache per-log scores; drop the stale copies
        print("cleared", cache)


if __name__ == "__main__":
    main()
